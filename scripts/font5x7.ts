export const GLYPH_HEIGHT = 7;

export function textWidth(text: string, scaleX = 1) {
	return text.length * 6 * scaleX - scaleX;
}

export function drawText(
	bitmap: Bitmap,
	x: number,
	y: number,
	text: string,
	scaleX = 1,
	scaleY = scaleX
): number {
	let cx = x;
	for (const ch of text.toUpperCase()) {
		const rows = (GLYPHS[ch] ?? GLYPHS[' ']).split(' ');
		rows.forEach((row, gy) => {
			for (let gx = 0; gx < 5; gx++) {
				if (row[gx] === '#') fillRect(bitmap, cx + gx * scaleX, y + gy * scaleY, scaleX, scaleY);
			}
		});
		cx += 6 * scaleX;
	}
	return cx - x - scaleX;
}
